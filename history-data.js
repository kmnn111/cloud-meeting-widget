function dayOfYear(d) {
  const start = new Date(d.getFullYear(), 0, 0);
  return Math.floor((d - start) / 86400000);
}

/* 小窗两行能完整显示的字符上限（340px 宽、12px 字号约 44 字，留少量余量）。
   联网条目动辄 60+ 字会溢出，优先挑长度合适的条目，实在没有才截断加省略号。 */
const PILL_MAX_CHARS = 42;

function pickOnline(list) {
  const scored = list.map(x => String(x || '').trim()).filter(Boolean);
  if (!scored.length) return null;
  const KEY = /会议|大会|全会|代表|召开|成立|解放|国庆|回归/;
  // 优先：命中会议类关键词 且 长度能完整显示 —— 取其中最短的（信息密度最高、最不挤）
  const ideal = scored.filter(s => KEY.test(s) && s.length <= PILL_MAX_CHARS && s.length >= 10)
    .sort((a, b) => a.length - b.length);
  if (ideal.length) return ideal[0];
  // 次选：任何能完整显示长度的条目
  const fits = scored.filter(s => s.length <= PILL_MAX_CHARS && s.length >= 10)
    .sort((a, b) => a.length - b.length);
  if (fits.length) return fits[0];
  // 兜底：关键词条目截断
  const kw = scored.find(s => KEY.test(s)) || scored[0];
  return kw.length > PILL_MAX_CHARS ? kw.slice(0, PILL_MAX_CHARS) + '…' : kw;
}

/**
 * 取当天的历史事件条目
 * @param {Date} date 日期
 * @param {Array<string>} online 可选的联网条目数组（优先）
 * @returns {{title: string, source: 'builtin'|'online'|'fallback', year: string|null}}
 */
function getToday(date = new Date(), online = null) {
  const key = String(date.getMonth() + 1).padStart(2, '0') + '-' + String(date.getDate()).padStart(2, '0');
  if (Array.isArray(online) && online.length) {
    const pick = pickOnline(online);
    if (pick) return { title: pick, source: 'online', year: (pick.match(/\d{4}/) || [null])[0] };
  }
  if (BY_DATE[key]) {
    return { title: BY_DATE[key], source: 'builtin', year: (BY_DATE[key].match(/\d{4}/) || [null])[0] };
  }
  const pick = FALLBACK_POOL[dayOfYear(date) % FALLBACK_POOL.length];
  return { title: pick, source: 'fallback', year: (pick.match(/\d{4}/) || [null])[0] };
}

